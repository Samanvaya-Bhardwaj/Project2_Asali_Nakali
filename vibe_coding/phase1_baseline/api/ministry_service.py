#!/usr/bin/env python3
"""
ministry_service.py
-------------------
Standalone HTTP RESTful Microservice representing DB4:
National Consumer Affairs Grievance Portal (INGRAM) & CDSCO Enforcement Service.

In real-world public governance, external commercial or clinical entities never
receive direct SQL access to national regulatory databases. Instead, government
portals expose secure RESTful APIs with bearer authentication, rate limits, and
standardized JSON payload envelopes.

Endpoints:
  GET  /api/v1/health                   - Health check and API version info
  GET  /api/v1/complaints?item_ref=...  - Consumer grievance complaints on file
  GET  /api/v1/blacklist?item_ref=...   - Gazette ban & blacklist records
  GET  /api/v1/lab_reports?item_ref=... - NABL accredited lab analysis reports
  GET  /api/v1/alerts?item_ref=...      - Public safety bulletins
  POST /api/v1/dossier                  - Submit automated incident dossier

Can be run as an independent background daemon:
    python3 api/ministry_service.py --port 8001
Or imported and called directly as an in-process fallback engine.
"""

from __future__ import annotations
import os, sys, json, sqlite3, argparse
from http.server import HTTPServer, BaseHTTPRequestHandler
from urllib.parse import urlparse, parse_qs
from datetime import datetime

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB_PATH = os.path.join(BASE, "databases", "db4_ministry_reports.sqlite")
DEFAULT_PORT = 8001
AUTH_TOKEN = "CDSCO-MCA-2026-KEY"


class MinistryDataStore:
    """Underlying data provider for the Ministry REST Service."""
    def __init__(self, db_path: str = DB_PATH):
        self.db_path = db_path

    def _get_conn(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        return conn

    def get_complaints(self, item_ref: str | None = None) -> list[dict]:
        conn = self._get_conn()
        try:
            cur = conn.cursor()
            if item_ref:
                cur.execute("SELECT * FROM complaints WHERE complaint_item_ref = ? ORDER BY complaint_date DESC", (item_ref,))
            else:
                cur.execute("SELECT * FROM complaints ORDER BY complaint_date DESC LIMIT 50")
            return [dict(r) for r in cur.fetchall()]
        finally:
            conn.close()

    def get_blacklist(self, item_ref: str | None = None) -> list[dict]:
        conn = self._get_conn()
        try:
            cur = conn.cursor()
            if item_ref:
                cur.execute("SELECT * FROM ministry_blacklist WHERE item_ref = ? AND active = 1", (item_ref,))
            else:
                cur.execute("SELECT * FROM ministry_blacklist WHERE active = 1")
            return [dict(r) for r in cur.fetchall()]
        finally:
            conn.close()

    def get_lab_reports(self, item_ref: str | None = None) -> list[dict]:
        conn = self._get_conn()
        try:
            cur = conn.cursor()
            if item_ref:
                cur.execute("SELECT * FROM lab_reports WHERE item_ref = ? ORDER BY test_completed_on DESC", (item_ref,))
            else:
                cur.execute("SELECT * FROM lab_reports ORDER BY test_completed_on DESC LIMIT 50")
            return [dict(r) for r in cur.fetchall()]
        finally:
            conn.close()

    def get_alerts(self, item_ref: str | None = None) -> list[dict]:
        conn = self._get_conn()
        try:
            cur = conn.cursor()
            if item_ref:
                cur.execute("SELECT * FROM public_alerts WHERE item_ref = ? AND active = 1 ORDER BY issued_on DESC", (item_ref,))
            else:
                cur.execute("SELECT * FROM public_alerts WHERE active = 1 ORDER BY issued_on DESC")
            return [dict(r) for r in cur.fetchall()]
        finally:
            conn.close()

    def create_dossier(self, dossier_payload: dict) -> dict:
        conn = self._get_conn()
        try:
            cur = conn.cursor()
            item_ref = dossier_payload.get("item_code") or dossier_payload.get("item_ref") or "UNKNOWN"
            complaint_id = f"MCA-2026-AUTO-{item_ref.replace('-', '')[-6:]}-{int(datetime.now().timestamp()) % 100000}"
            desc = dossier_payload.get("description") or "Automated incident report generated by Asali Federated Verification Engine."
            
            cur.execute("""
                INSERT OR REPLACE INTO complaints (
                    complaint_id, complaint_item_ref, complaint_date, complainant_type,
                    complainant_name, complainant_contact, purchase_location,
                    complaint_category, description, severity_level, status,
                    assigned_officer_id, date_assigned, auto_generated
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1)
            """, (
                complaint_id,
                item_ref,
                datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                "automated_ai_sentinel",
                "Asali Federated Integration Engine",
                "sentinel@asali-audit.gov.in",
                dossier_payload.get("location") or "Retail Dispensary POS",
                dossier_payload.get("category") or "counterfeit",
                desc,
                "critical",
                "under_investigation",
                "OFF-001",
                datetime.now().strftime("%Y-%m-%d")
            ))
            conn.commit()
            return {
                "dossier_id": complaint_id,
                "item_ref": item_ref,
                "status": "registered",
                "timestamp": datetime.now().isoformat(),
                "assigned_officer": "Dr. Rajesh Sharma (Senior Drug Inspector, CDSCO)"
            }
        finally:
            conn.close()


GLOBAL_DATASTORE = MinistryDataStore()


class MinistryApiHandler(BaseHTTPRequestHandler):
    """HTTP Request Handler implementing RESTful endpoints for DB4."""

    def _set_headers(self, status: int = 200, content_type: str = "application/json"):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Server", "CDSCO-INGRAM-Microservice/3.4")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
        self.end_headers()

    def do_OPTIONS(self):
        self._set_headers(204)

    def do_GET(self):
        parsed = urlparse(self.path)
        path = parsed.path
        params = parse_qs(parsed.query)
        item_ref = params.get("item_ref", [None])[0]

        if path == "/api/v1/health":
            self._set_headers(200)
            payload = {
                "status": "online",
                "service": "Ministry of Consumer Affairs & CDSCO National Portal (INGRAM API)",
                "version": "3.4.1-gov",
                "protocol": "REST/JSON",
                "timestamp": datetime.now().isoformat(),
                "authorized": True
            }
            self.wfile.write(json.dumps(payload, indent=2).encode("utf-8"))

        elif path == "/api/v1/complaints":
            records = GLOBAL_DATASTORE.get_complaints(item_ref)
            self._set_headers(200)
            payload = {
                "meta": {
                    "source": "DB4 - Ministry of Consumer Affairs Grievance Portal",
                    "query_param": {"item_ref": item_ref},
                    "count": len(records),
                    "retrieved_at": datetime.now().isoformat()
                },
                "data": records
            }
            self.wfile.write(json.dumps(payload, indent=2).encode("utf-8"))

        elif path == "/api/v1/blacklist":
            records = GLOBAL_DATASTORE.get_blacklist(item_ref)
            self._set_headers(200)
            payload = {
                "meta": {
                    "source": "DB4 - CDSCO National Gazette Blacklist",
                    "query_param": {"item_ref": item_ref},
                    "count": len(records),
                    "retrieved_at": datetime.now().isoformat()
                },
                "data": records
            }
            self.wfile.write(json.dumps(payload, indent=2).encode("utf-8"))

        elif path == "/api/v1/lab_reports":
            records = GLOBAL_DATASTORE.get_lab_reports(item_ref)
            self._set_headers(200)
            payload = {
                "meta": {
                    "source": "DB4 - Central Drug Laboratory (CDL) Testing Registry",
                    "query_param": {"item_ref": item_ref},
                    "count": len(records),
                    "retrieved_at": datetime.now().isoformat()
                },
                "data": records
            }
            self.wfile.write(json.dumps(payload, indent=2).encode("utf-8"))

        elif path == "/api/v1/alerts":
            records = GLOBAL_DATASTORE.get_alerts(item_ref)
            self._set_headers(200)
            payload = {
                "meta": {
                    "source": "DB4 - Ministry Public Safety Alert Broadcast",
                    "query_param": {"item_ref": item_ref},
                    "count": len(records),
                    "retrieved_at": datetime.now().isoformat()
                },
                "data": records
            }
            self.wfile.write(json.dumps(payload, indent=2).encode("utf-8"))

        else:
            self._set_headers(404)
            self.wfile.write(json.dumps({"error": "Endpoint not found", "path": path}).encode("utf-8"))

    def do_POST(self):
        parsed = urlparse(self.path)
        if parsed.path == "/api/v1/dossier":
            length = int(self.headers.get("Content-Length", 0))
            raw_data = self.rfile.read(length) if length > 0 else b"{}"
            try:
                payload = json.loads(raw_data.decode("utf-8"))
            except Exception:
                payload = {}
            result = GLOBAL_DATASTORE.create_dossier(payload)
            self._set_headers(201)
            self.wfile.write(json.dumps({"status": "success", "result": result}, indent=2).encode("utf-8"))
        else:
            self._set_headers(404)
            self.wfile.write(json.dumps({"error": "Endpoint not found"}).encode("utf-8"))

    def log_message(self, format, *args):
        # Silent or concise logging to avoid stdout clutter
        pass


def run_server(port: int = DEFAULT_PORT):
    server = HTTPServer(("127.0.0.1", port), MinistryApiHandler)
    print(f"  [DB4 REST Microservice] Running at http://127.0.0.1:{port}/api/v1/")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n  [DB4 REST Microservice] Shutting down.")
        server.server_close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Ministry of Consumer Affairs REST Microservice")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT, help="Port to bind (default: 8001)")
    args = parser.parse_args()
    run_server(args.port)
